/**
 * A minimal Queue implementation (FIFO - First In First Out).
 */
export class Queue {
  constructor(initialItems = []) {
    this.items = [...initialItems];
  }

  enqueue(item) {
    this.items.push(item);
  }

  dequeue() {
    return this.items.shift();
  }

  peek() {
    return this.items[0];
  }

  isEmpty() {
    return this.items.length === 0;
  }

  size() {
    return this.items.length;
  }

  toArray() {
    return [...this.items];
  }
}
